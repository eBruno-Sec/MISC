"""Q-007 — an effect must belong to an engine that EXISTS.

The defect, MEASURED before any of this was written: `engine_descriptor.conflicts()` returned six rows
and ALL SIX were generated by `weak_password_reset`, which had no executor on any surface. It was the
only one of 13 `EFFECTS` entries with a non-empty `invalidates`, so the whole negative half of the
planner's model — the Sussman half, the reason `effect_search` is a search and not a graph walk — was
generated by an engine that does not exist. A second entry, `soft_deleted_login`, had the same shape
with `establishes: ["authenticated"]`.

THE NEGATIVE CONTROLS COME FIRST IN THIS FILE, DELIBERATELY, and they were run first as probes before
the fix was applied. This codebase has shipped a guard that checks a declaration instead of a fact
eight times, and this ticket is one of them coming home: the standing recommendation was to
"set `solver_only=True` (the field exists)" and the field exists on 0 of 88 records. So every
clean-sheet assertion below is preceded by a test proving the same apparatus reports a dirty one.
"""

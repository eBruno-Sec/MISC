# ── NEGATIVE CONTROLS ───────────────────────────────────────────────────────────────────────────

def test_the_guard_fails_on_the_table_it_was_written_to_catch():
    """The one that matters. Run the guard against the REAL pre-fix table and it must reject it, naming
    both phantoms. If this ever passes, the guard has stopped seeing the defect it exists for."""
    a = ed.effects_audit(effects=HISTORICAL_2026_08_17)
    assert a["ok"] is False
    assert "weak_password_reset" in a["no_engine_declared"]
    assert "soft_deleted_login" in a["no_engine_declared"]
    assert a["checked"] == 13


def test_the_guard_fails_on_an_invented_engine_name():
    """The mutation. Re-arm the phantom and give it the name it would have had if anyone had built it."""
    mut = copy.deepcopy(ed.EFFECTS)
    mut["weak_password_reset"] = {"establishes": ["authenticated"],
                                  "invalidates": ["authenticated"],
                                  "engine": ["run_weak_password_reset"]}
    a = ed.effects_audit(effects=mut)
    assert a["ok"] is False
    assert a["unregistered"] == ["weak_password_reset -> run_weak_password_reset"]
    assert a["unimplemented"] == ["weak_password_reset -> run_weak_password_reset"]


def test_a_phantom_engine_also_fails_the_routing_audit(monkeypatch):
    """Two independent nets, not one. `routing_audit()` scans the same declaration by MEMBERSHIP (not by
    the `run_|confirm_` shape filter it uses on prose, so a typo like `defualt_creds` cannot slip
    through), and its `phantom` list is already the load-bearing invariant the platform ships."""
    armed = copy.deepcopy(ed.EFFECTS)
    armed["weak_password_reset"] = {"establishes": ["authenticated"], "invalidates": ["authenticated"],
                                    "engine": ["run_weak_password_reset"]}
    monkeypatch.setattr(ed, "EFFECTS", armed)
    a = ed.routing_audit()
    assert a["ok"] is False
    assert a["phantom"] == ["weak_password_reset (effect_engine) -> run_weak_password_reset"]

    misspelled = copy.deepcopy(ed.EFFECTS)
    misspelled["default_credentials"] = dict(misspelled["default_credentials"],
                                             engine=["defualt_creds"])
    monkeypatch.setattr(ed, "EFFECTS", misspelled)
    a = ed.routing_audit()
    assert a["ok"] is False, "a non-engine-shaped typo slipped through the membership check"


def test_the_guard_fails_when_a_declared_engine_is_registered_but_not_implemented():
    """Registration and implementation are two different facts and this checks both. MEASURED today,
    `TOOL_PERMISSIONS - implementations` is EMPTY, so this cannot fire on a real registered name — the
    control therefore synthesises the divergence rather than pretending the tree contains one."""
    assert not (set(TL.TOOL_PERMISSIONS) - ed.engine_implementations()), \
        "a registered name lost its implementation; re-measure before editing this test"
    a = ed.effects_audit(implementations=ed.engine_implementations() - {"run_jwt"})
    assert a["ok"] is False
    assert a["unregistered"] == [], "the registry half must be unaffected"
    assert a["unimplemented"] == ["jwt_forge -> run_jwt", "jwt_key_confusion -> run_jwt"]


def test_the_guard_fails_closed_when_a_fact_table_cannot_be_read():
    """An instrument that loaded nothing must never report a clean sheet."""
    assert ed.effects_audit(registry=set())["ok"] is False
    assert ed.effects_audit(implementations=set())["ok"] is False


def test_the_guard_is_not_vacuous():
    """A scan over an empty set passes for free, which is the defect, not the fix."""
    empty = ed.effects_audit(effects={})
    assert empty["ok"] is False
    assert empty["checked"] == 0
    live = ed.effects_audit()
    assert live["checked"] >= 11
    assert live["registry_size"] > 100
    assert live["implementations_size"] > 100
    assert live["cross_checked_against_derived_route"] >= 9, \
        "no declaration was compared against an independently derived route"


